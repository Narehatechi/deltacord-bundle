/** Dependency-free 53-bit hash (cyrb53), used to detect damaged or truncated backups. */
export function checksum(text: string): string {
    let h1 = 0xdeadbeef, h2 = 0x41c6ce57;
    for (let i = 0; i < text.length; i++) {
        const c = text.charCodeAt(i);
        h1 = Math.imul(h1 ^ c, 2654435761);
        h2 = Math.imul(h2 ^ c, 1597334677);
    }
    h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
    h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
    return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(16);
}

/** Hashes the files in a stable order so key order never changes the result. */
export function checksumFiles(files: Record<string, string>): string {
    return checksum(Object.keys(files).sort().map(k => `${k}\0${files[k]}`).join("\0\0"));
}
